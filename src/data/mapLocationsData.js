// Hàm tạo link chỉ đường Google Maps chuẩn từ tọa độ hoặc link có sẵn
export function buildGoogleMapsDirectionUrl(toado, customLink = '') {
  if (customLink && customLink.startsWith('http')) {
    return customLink;
  }
  if (Array.isArray(toado) && toado.length === 2) {
    return `https://www.google.com/maps/dir/?api=1&destination=${toado[0]},${toado[1]}`;
  }
  return 'https://www.google.com/maps';
}

